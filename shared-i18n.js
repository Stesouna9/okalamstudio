// ── Apply page translations ──
function applyPageTranslations(l) {
  const t = PAGE_T[l] || PAGE_T.en;
  const bl = PAGE_T[l] ? l : 'en';
  document.querySelectorAll('img[data-badge]').forEach(i => { const k = i.getAttribute('data-badge'); i.src = 'imgs/badges/' + k + '_' + bl + (k === 'appstore' ? '.svg' : '.png'); });

  // Discord pill (all pages) — invite VICE BREAK
  let pill = document.getElementById('ok-disc-pill');
  if (!pill && !document.querySelector('.vbr')) {
    pill = document.createElement('a');
    pill.id = 'ok-disc-pill';
    pill.href = 'https://discord.gg/TSaxEnt2dG';
    pill.target = '_blank'; pill.rel = 'noopener';
    pill.style.cssText = 'position:fixed;left:50%;bottom:14px;transform:translateX(-50%);z-index:9998;padding:10px 18px;border-radius:999px;background:#5865F2;color:#fff;font:600 14px/1.2 "DM Sans",system-ui,sans-serif;text-decoration:none;box-shadow:0 6px 24px rgba(0,0,0,.35);white-space:nowrap;max-width:calc(100vw - 32px);overflow:hidden;text-overflow:ellipsis;transition:transform .15s';
    pill.onmouseenter = () => pill.style.transform = 'translateX(-50%) scale(1.04)';
    pill.onmouseleave = () => pill.style.transform = 'translateX(-50%)';
    document.body.appendChild(pill);
  }
  if (pill) pill.textContent = t.disc_pill || PAGE_T.en.disc_pill;

  // data-i18n attributes (innerHTML for those with HTML tags)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      // Use innerHTML for entries that might contain <em>, <strong>, <span>
      el.innerHTML = t[key];
    }
  });

  // id-based elements (collaborations + contact pages)
  const idKeys = [
    'c_sub','c_what_lead','c_what_p1','c_what_p2','c_what_p3',
    'c_what_label',
    'c_v1_t','c_v1_d','c_v2_t','c_v2_d','c_v3_t','c_v3_d',
    'c_serv_title',
    'c_s1_t','c_s1_d','c_s2_t','c_s2_d','c_s3_t','c_s3_d','c_s4_t','c_s4_d',
    'c_cr_label','c_cr_title','c_cr_note',
    'c_p1_niche','c_p1_title','c_p1_desc','c_p1_btn',
    'c_p2_niche','c_p2_title','c_p2_desc','c_p2_btn',
    'c_b_title','c_b_sub',
    'c_bc1_d','c_bc2_t','c_bc2_d','c_bc3_t','c_bc3_d',
  ];
  idKeys.forEach(key => {
    const el = document.getElementById(key);
    if (el && t[key] !== undefined) el.innerHTML = t[key];
  });

  // Nav links
  const navMap = {
    'studio.html':'nav_studio','projets.html':'nav_projects',
    'collaborations.html':'nav_collabs','contact.html':'nav_contact'
  };
  document.querySelectorAll('.ok-nav-link, .ok-nav-cta').forEach(a => {
    const href = a.getAttribute('href');
    if (href && navMap[href] && t[navMap[href]]) a.textContent = t[navMap[href]];
  });
}
